const { z } = require('zod');
module.exports = z.array(z.object({
        action: z.enum(['navigate', 'click', 'tap', 'dblclick', 'hover', 'type', 'press', 'scroll', 'wait_for', 'set_viewport', 'screenshot', 'get_text', 'count', 'eval', 'assert', 'back', 'reload']),
        url: z.string().optional(),
        selector: z.string().optional(),
        text: z.string().optional().describe('Texto a escribir cuando action="type"; cuando es un localizador se usa con click/get_text/assert'),
        value: z.string().optional().describe('Alias explicito del texto a escribir en "type" (evita ambiguedad con selector)'),
        role: z.string().optional(),
        name: z.string().optional(),
        label: z.string().optional(),
        placeholder: z.string().optional(),
        alt: z.string().optional(),
        testId: z.string().optional(),
        key: z.string().optional(),
        to: z.enum(['top', 'bottom']).optional(),
        y: z.number().optional(),
        width: z.number().int().optional(),
        height: z.number().int().optional(),
        expression: z.string().optional().describe('JS a evaluar en la pagina cuando action="eval"; debe retornar algo serializable a JSON. Ojo: en pantalla emulada window.innerWidth es el ANCHO DEL LAYOUT, que puede superar al dispositivo si el contenido desborda; para el ancho real usá window.visualViewport.width'),
        count: z.number().int().optional(),
        visible: z.boolean().optional(),
        urlIncludes: z.string().optional(),
        fullPage: z.boolean().optional(),
        ms: z.number().int().min(0).max(30000).optional(),
        waitUntil: z.enum(['load', 'domcontentloaded', 'networkidle', 'commit']).optional(),
        timeoutMs: z.number().int().min(500).max(120000).optional(),
        clear: z.boolean().optional(),
        force: z.boolean().optional(),
        exact: z.boolean().optional(),
        delay: z.number().int().min(0).max(500).optional().describe('Retraso por caracter al escribir con type+clear:false'),
        state: z.enum(['attached', 'detached', 'hidden', 'visible']).optional(),
      })).min(1).max(40).describe('Pasos en orden, maximo 40');
